import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const pkg=JSON.parse(fs.readFileSync(new URL('../package.json',import.meta.url),'utf8'));
const m=pkg.version.match(/^(\d+)\.(\d+)\.(\d+)(?:-rc(?:\.(\d+))?)?$/);
assert.ok(m,'package version is neither stable nor RC semver');
const isRc=/-rc(?:\.|$)/.test(pkg.version);
const display=`MindDeck V${m[1]}.${m[2]}.${m[3]}${isRc?' RC':''}`;
assert.ok(html.includes(display),`release version mismatch: ${display}`);
const channel=isRc?'rc':'stable';
for(const marker of ['id="welcomeOverlay"','id="helpBtn"','data-mm="help"','function showWelcome(force=false)','function closeWelcome()','minddeck-v9-onboarded',`RELEASE_CHANNEL="${channel}"`,'Portable Runtime ${RUNTIME_VERSION}','id="masterSettingsBtn"','function showMasterSettingsPanel()','PresentationViewCore.create({','MapRendererCore.render(','function renderToc(){return presentationView?.renderToc()}','DiagnosticsCore.inspect(','MindDeckCore.Portable.mount']) assert.ok(html.includes(marker),`release contract missing: ${marker}`);
for(const blocker of ['TODO_RELEASE_BLOCKER','FIXME_RELEASE_BLOCKER']) assert.ok(!html.includes(blocker),`release blocker present: ${blocker}`);
console.log(`Release contracts: OK (16 checks, ${display}, ${channel})`);
